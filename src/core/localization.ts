/** Translates split text nodes that only occur in Route Finder's nested summary. */
export function translateRouteFinderUiText(value: string): string | undefined {
  const text = value.replace(/\s+/g, ' ').trim();
  const exact = ROUTE_FINDER_FRAGMENT_TRANSLATIONS[text];
  if (exact) {
    return exact;
  }

  const summary = text.match(
    /^Sorted by (Climb Area|Area|Difficulty|Popularity|Name) then (Climb Area|Area|Difficulty|Popularity|Name)\. Results (\d+) to (\d+) of ([\d,]+)\.$/,
  );
  if (summary) {
    const [, primary = '', secondary = '', start = '', end = '', total = ''] = summary;
    const primaryLabel = ROUTE_FINDER_FRAGMENT_TRANSLATIONS[primary]
      ?? translateUiText(primary)
      ?? primary;
    const secondaryLabel = ROUTE_FINDER_FRAGMENT_TRANSLATIONS[secondary]
      ?? translateUiText(secondary)
      ?? secondary;
    return `${primaryLabel}, ${secondaryLabel} 순으로 정렬 · 결과 ${start}~${end} / 총 ${total}개`;
  }

  return undefined;
}

