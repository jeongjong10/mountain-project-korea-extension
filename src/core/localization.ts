/** Translates only the site-owned labels used by the classic-vote component. */
export function translateClassicVoteUiText(value: string): string | undefined {
  const text = value.replace(/\s+/g, ' ').trim();
  const exact = CLASSIC_VOTE_UI_TEXT_TRANSLATIONS[text];
  if (exact) {
    return exact;
  }

  const patterns: Array<[RegExp, (...groups: string[]) => string]> = [
    [/^([\d,]+) votes?$/, (count) => `${count}표`],
    [/^Classic votes?:\s*([\d,]+)$/i, (count) => `클래식 투표 ${count}표`],
    [/^([\d,]+) climbers? voted this a classic\.?$/i, (count) => `${count}명이 클래식으로 추천했습니다.`],
  ];
  for (const [pattern, format] of patterns) {
    const match = text.match(pattern);
    if (match) {
      return format(...match.slice(1));
    }
  }
  return undefined;
}

